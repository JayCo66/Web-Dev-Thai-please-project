const categories = {
  EDUCATION: "education",
  ENVIRONMENT: "environment",
  COMMUNITY: "community",
  HEALTHCARE: "healthcare",
};
function charityMedia(charity) {
  const asset = media[charity.name];
  const kind =
    asset?.kind ||
    (asset?.cover ? "photo" : asset?.logo ? "logo" : "illustration");
  const cover =
    asset?.cover ||
    asset?.logo ||
    `${categories[charity.impact_type] || "community"}-illustration.jpg`;
  return {
    coverImageUrl: `/assets/charities/${cover}`,
    logoImageUrl: asset?.logo ? `/assets/charities/${asset.logo}` : null,
    imageKind: kind,
    imagePosition: asset?.position || "center",
    imageCaption:
      asset?.caption ||
      (kind === "logo" ? "ตราสัญลักษณ์มูลนิธิ" : "ภาพประกอบหมวดหมู่"),
    websiteUrl: asset?.website || null,
  };
}
module.exports = { charityMedia };
